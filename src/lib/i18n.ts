/**
 * Español e inglés. El español es el idioma de respaldo: si falta una
 * traducción de un producto, se muestra el español en vez de dejar el hueco.
 */

import type { Idioma, Texto } from "./tipos";

export const IDIOMAS: Idioma[] = ["es", "en"];
export const IDIOMA_POR_DEFECTO: Idioma = "es";
export const COOKIE_IDIOMA = "proinshop_idioma";

export function esIdiomaValido(valor: string | undefined): valor is Idioma {
  return valor === "es" || valor === "en";
}

/** Toma el texto en el idioma pedido, con respaldo al español. */
export function texto(valor: Texto, idioma: Idioma): string {
  const elegido = valor[idioma]?.trim();
  return elegido && elegido.length > 0 ? elegido : valor.es;
}

export function formatearPrecio(valor: number): string {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: valor % 1 === 0 ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(valor);
}

